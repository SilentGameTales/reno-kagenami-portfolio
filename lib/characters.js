export function getFaction(character) {
  if (character.faction) return character.faction;
  const tags = character.tags || [];
  if (tags.includes("Black Meridian")) return "Black Meridian";
  if (tags.includes("Truthrunner Network")) return "Truthrunner Network";
  if (tags.includes("Stillwake Triumvirate")) return "Stillwake";
  if (tags.includes("Felix Bloodline") || tags.includes("Empire") || character.id === "king-felix-iv") return "Imperial Crown";
  if (["reno","jinvar","izanara","alaster","alice","elara-viremont","amaya","hikari-starbright"].includes(character.id)) return "Core Cast";
  return "Independent";
}
